    <strong style="display:block; margin-bottom:.5rem;">Как получить координаты офиса:</strong>
    <ol style="margin:0; padding-left:1.25rem; list-style:decimal;">
        <li>Открой <a href="https://yandex.ru/maps/" target="_blank" style="color:#2563eb; text-decoration:underline;">Yandex Maps</a> или <a href="https://www.google.com/maps" target="_blank" style="color:#2563eb; text-decoration:underline;">Google Maps</a></li>
        <li>Найди свой офис на карте, наведи курсор точно на здание</li>
        <li>Правый клик по метке → <strong>«Что здесь»</strong> (Yandex) или сами координаты (Google)</li>
        <li>Скопируй два числа через запятую: сначала <em>широта</em> (41.xxx), потом <em>долгота</em> (69.xxx)</li>
        <li>Вставь в поля выше и сохрани</li>
    </ol>
    <p style="margin:.75rem 0 0; font-size:.8rem; color:#3730a3;">
        Пример для центра Ташкента: <code style="background:#dbeafe; padding:.1rem .4rem; border-radius:3px;">41.311081, 69.240562</code>
    </p>
</div>
